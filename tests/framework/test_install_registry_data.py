def _git(target: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(target), "-c", "commit.gpgsign=false", *args],
        capture_output=True,
        text=True,
        check=check,
    )


def _git_init_target(base: Path) -> Path:
    target = base / "target"
    target.mkdir()
    subprocess.run(["git", "init", str(target)], capture_output=True, check=True)
    _git(target, "config", "user.email", "test@example.com")
    _git(target, "config", "user.name", "Test")
    return target


def _run_installer(target: Path, *extra_args: str) -> subprocess.CompletedProcess:
    env = {**os.environ, "HOS_NO_CONFIG": "1"}
    return subprocess.run(
        ["bash", str(INSTALL_SH), "--local", str(target), *extra_args],
        capture_output=True,
        text=True,
        env=child_env(env),
        input="\n",
    )


def _install_ok(target: Path, *extra_args: str) -> subprocess.CompletedProcess:
    r = _run_installer(target, *extra_args)
    assert r.returncode == 0, r.stdout + r.stderr
    return r


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _manifest_rows(target: Path) -> list[list[str]]:
    rows = []
    for line in (target / ".hos-manifest").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            rows.append(line.split("\t"))
    return rows


def _whole_rows_for(target: Path, path: str) -> list[list[str]]:
    return [r for r in _manifest_rows(target) if r[0] == path and r[1] == "WHOLE"]


def _gitattributes_lines(target: Path) -> list[str]:
    return (target / ".gitattributes").read_text(encoding="utf-8").splitlines()


def _commit_all(target: Path) -> None:
    _git(target, "add", "-A")
    _git(target, "commit", "-q", "-m", "install")


def _recheckout_with_autocrlf(target: Path) -> None:
    """Simulate a fresh clone on an autocrlf=true machine."""
    _git(target, "config", "core.autocrlf", "true")
    subprocess.run(
        ["rm", "-rf", str(target / "contract"), str(target / ".hos-manifest")], check=True
    )
    _git(target, "checkout", "--", ".")


