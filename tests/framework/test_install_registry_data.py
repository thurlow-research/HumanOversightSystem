@pytest.mark.slow
def test_t5_69_gitattributes_lines_once_and_idempotent(tmp_path):
    target = _git_init_target(tmp_path)
    _install_ok(target, "--pack", "django")
    for line in GITATTRIBUTES_LINES:
        assert _gitattributes_lines(target).count(line) == 1
    _install_ok(target, "--pack", "django")
    for line in GITATTRIBUTES_LINES:
        assert _gitattributes_lines(target).count(line) == 1


@pytest.mark.slow
def test_t5_69_autocrlf_checkout_stays_green_and_control_drifts(tmp_path):
    target = _git_init_target(tmp_path)
    _install_ok(target, "--pack", "django")
    _commit_all(target)
    _recheckout_with_autocrlf(target)
    assert dr.load(target).packs == ("django",)
    attr = _git(target, "check-attr", "text", "--", "contract/dimensions/prompts/ui.md").stdout
    assert attr.strip().endswith("text: unset")

    # Control: without the attributes, the same re-checkout must drift.
    _git(target, "config", "core.autocrlf", "false")
    (target / ".gitattributes").write_text("", encoding="utf-8")
    _git(target, "add", "-A")
    _git(target, "commit", "-q", "-m", "drop attributes")
    _recheckout_with_autocrlf(target)
    # Without -text the checkout rewrote the HOS-hashed files to CRLF.
    assert b"\r\n" in (target / "contract" / "resolved-packs.txt").read_bytes()
    assert b"\r\n" in (target / "contract" / "dimensions" / "core.yaml").read_bytes()
    # L24 parses resolved-packs.txt before L31 hashes it, so "invalid pack slug"
    # is the first failure under CRLF (TD-VF-39's installed_drift expectation is
    # pre-empted); this proves the green case above discriminates.
    with pytest.raises(dr.RegistryError, match="invalid pack slug"):
        dr.load(target)


