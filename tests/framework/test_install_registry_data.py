def _installer_lines() -> list[str]:
    return INSTALL_SH.read_text(encoding="utf-8").splitlines()


def test_t5_44_registry_kinds_table_matches_engine():
    text = INSTALL_SH.read_text(encoding="utf-8")
    m = re.search(r"^_REGISTRY_KINDS=\(([^)]*)\)", text, re.M)
    assert m, "_REGISTRY_KINDS=( ... ) literal not found in hos_install.sh"
    rows = re.findall(r'"([^"]+)"', m.group(1))
    parsed = {tuple(row.split(":", 1)) for row in rows}
    assert len(parsed) == len(rows), "duplicate _REGISTRY_KINDS rows"
    assert parsed == {(k.pack_source, k.directory) for k in dr.KINDS.values()}


def test_t5_44_resolved_pack_dirs_appended_once_in_r3_loop():
    lines = _installer_lines()
    hits = [i for i, ln in enumerate(lines) if "_resolved_pack_dirs+=" in ln]
    assert len(hits) == 1, f"expected exactly one _resolved_pack_dirs+=, got {len(hits)}"
    i = hits[0]
    # The append sits in the R3 loop, directly after _resolve_pack_dir succeeds.
    loop_start = max(j for j in range(i) if lines[j].startswith("for _p in "))
    assert "_resolve_pack_dir" in "\n".join(lines[loop_start:i])
    assert "_resolved_packs" in lines[loop_start]


def test_t5_44_registry_block_never_calls_resolve_pack_dir():
    lines = _installer_lines()
    start = next(i for i, ln in enumerate(lines) if "registry data (ADR-1643 TD-D31/D32/D54)" in ln)
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("# ── audit/"))
    code = [ln for ln in lines[start:end] if not ln.lstrip().startswith("#")]
    assert not any("_resolve_pack_dir" in ln for ln in code)


