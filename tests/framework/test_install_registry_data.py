@pytest.mark.slow
def test_t5_47_drift_blocked_install_writes_no_registry_data(tmp_path):
    target = _git_init_target(tmp_path)
    _install_ok(target, "--pack", "django")
    agent = target / ".claude" / "agents" / "code-reviewer.md"
    original = agent.read_bytes()
    marker = b"<!-- HOS:PACK:django:START -->"
    assert marker in original, "PACK:django region marker not found in code-reviewer.md"
    start = original.index(marker) + len(marker)
    edited = original[:start] + b"\nCONSUMER EDITED PACK BODY\n" + original[start:]
    agent.write_bytes(edited)
    pack_file = target / "contract" / "dimensions" / "pack-django.yaml"
    pack_file.unlink()
    resolved = target / "contract" / "resolved-packs.txt"
    resolved_before = resolved.read_bytes()

    r = _run_installer(target, "--pack", "django")
    assert r.returncode == 4, r.stdout + r.stderr
    assert resolved.read_bytes() == resolved_before, "aborted install rewrote resolved-packs.txt"
    assert not pack_file.exists(), "Phase A abort must precede the registry-data step"


