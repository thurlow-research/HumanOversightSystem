def test_t5_71_ensure_line_exact_scoping():
    calls = [
        ln.strip()
        for ln in _installer_lines()
        if re.match(r"\s*(\$ROLE_HUMAN && )?ensure_line\b", ln)
    ]
    # Multi-line calls: only the first physical line carries the target argument.
    gitignore = [c for c in calls if '"$GITIGNORE"' in c]
    gitattrs = [c for c in calls if "_GITATTRIBUTES" in c]
    assert len(gitignore) == 8
    assert len(gitattrs) == 3
    text = INSTALL_SH.read_text(encoding="utf-8")
    # A call spans to the first line not ending in a backslash continuation.
    for m in re.finditer(r"ensure_line\s+\"\$GITIGNORE\"(?:[^\n]*\\\n)*[^\n]*", text):
        assert not re.search(r"\bexact\b", m.group(0)), m.group(0)
    for c in gitattrs:
        assert c.endswith("exact"), c


