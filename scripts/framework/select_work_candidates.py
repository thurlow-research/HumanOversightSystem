def main(argv: Optional[list] = None) -> int:
    parser = _build_parser()
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        # argparse's own usage-error exit is 2, which is consistent: a
        # malformed invocation is a fail-closed condition (§2.2).
        return exc.code if isinstance(exc.code, int) else 2

    effective_max_candidates = min(_DEFAULT_MAX_CANDIDATES, max(1, args.max_candidates))
    effective_max_api_requests = min(_DEFAULT_MAX_API_REQUESTS, max(0, args.max_api_requests))

    repo_root = str(_REPO_ROOT)
    budget = _Budget(effective_max_api_requests)

    try:
        config = _load_configuration(repo_root, args.repo, budget)
    except _ConfigFailure as exc:
        _emit(exc.token)
        if exc.remediation:
            _emit(exc.remediation)
        return 2
    except Exception:  # noqa: BLE001 — Step B's own catch-all (§2.3 Step B item 7)
        _emit("config-error")
        return 2

    # Step C — the paginated list query. `--label` is URL-encoded before
    # embedding: a space is a legal GitHub label character (e.g. "needs ai")
    # that `_label_name` does not and must not reject, but an unencoded space
    # produces a malformed querystring (cross-vendor second review, agy).
    encoded_label = urllib.parse.quote(args.label, safe="")

    def list_endpoint(page: int) -> str:
        return (
            f"repos/{args.repo}/issues?state=open&milestone={args.milestone}"
            f"&labels={encoded_label}&per_page=100&page={page}"
        )

    outcome = _fetch_pages(list_endpoint, LIST_PAGE_BOUND, budget)
    if outcome.state == "FAILED":
        _emit("list-query-failed")
        return 2

    filtered = _apply_free_filters(outcome.records)
    candidates_raw = filtered.kept
    scanned = len(candidates_raw) + len(filtered.unreadable)
    list_truncated = outcome.state == "BOUND-REACHED"
    ceiling_refused_at_list = outcome.state == "REFUSED"

    if ceiling_refused_at_list:
        # "The gate does not walk a partial list." Nothing is admitted.
        # Every fetched-and-filtered record counts as unevaluated:cost-ceiling
        # (§2.3 Step C REFUSED state). No WARN — the ceiling is routine. D2b
        # is free and already ran (§2.5): only `kept` records are
        # cost-ceiling; unreadable ones are their own named reason.
        return _report_and_exit(
            repo=args.repo,
            milestone=args.milestone,
            scanned=scanned,
            eligible=[],
            gated_reasons=Counter(),
            gated_issue_numbers=[],
            authorized={},
            unevaluated_sufficient=0,
            unevaluated_cost_ceiling=len(candidates_raw),
            cost_ceiling_named_issue=None,
            query_failed_issues=[],
            list_truncated=False,
            tier_degraded=config.tier_degraded,
            tier_count=config.tier_count,
            collaborator_bound_reached=config.collaborator_bound_reached,
            api_requests=budget.spent,
            walk_warn_lines=[],
            ceiling_refused_at_list=True,
            edge_summary_unreadable=filtered.unreadable,
            excluded=filtered.excluded,
        )

    # D3/D4/D-rank — free, computed over the whole (post-D1/D2) set.
    candidate_states = [
        _Candidate(
            number=r.get("number"),
            title=_sanitize_title(r.get("title") or ""),
            rank=_rank(r),
            verdict=requester_verdict(r, config.trusted_set),
            record=r,
        )
        for r in candidates_raw
    ]
    stages = _started_stages(repo_root, [c.number for c in candidate_states])
    if stages is None:
        _emit("WARN started-signal-unavailable")
    else:
        for c in candidate_states:
            c.stage = stages.get(c.number, _STAGE_NONE)
    walk_order = sorted(candidate_states, key=lambda c: (c.stage, c.rank, -c.number))

    walk_result = _walk(
        walk_order,
        repo=args.repo,
        label=args.label,
        codeowners=config.codeowners,
        bots=config.bots,
        budget=budget,
        max_candidates=effective_max_candidates,
    )

    emit_order = sorted(walk_result.eligible, key=lambda c: (c.stage, c.rank, c.number))
    for c in emit_order:
        marker = f" [started:{_STAGE_NAMES[c.stage]}]" if c.stage in _STAGE_NAMES else ""
        print(f"#{c.number} [{_PRIORITY_NAMES[c.rank]}]{marker} {c.title}")
    _emit(
        f"STARTED branch={sum(c.stage == _STAGE_BRANCH for c in emit_order)}",
        f"design={sum(c.stage == _STAGE_DESIGN for c in emit_order)}",
    )

    return _report_and_exit(
        repo=args.repo,
        milestone=args.milestone,
        scanned=scanned,
        eligible=walk_result.eligible,
        gated_reasons=walk_result.gated_reasons,
        gated_issue_numbers=walk_result.gated_issue_numbers,
        authorized=walk_result.authorized,
        unevaluated_sufficient=walk_result.unevaluated_sufficient,
        unevaluated_cost_ceiling=walk_result.unevaluated_cost_ceiling,
        cost_ceiling_named_issue=walk_result.cost_ceiling_named_issue,
        query_failed_issues=walk_result.query_failed_issues,
        list_truncated=list_truncated,
        tier_degraded=config.tier_degraded,
        tier_count=config.tier_count,
        collaborator_bound_reached=config.collaborator_bound_reached,
        api_requests=budget.spent,
        walk_warn_lines=walk_result.warn_lines,
        edge_summary_unreadable=filtered.unreadable,
        excluded=filtered.excluded,
    )


if __name__ == "__main__":  # pragma: no cover - CLI entry, exercised via subprocess only
    sys.exit(main())
