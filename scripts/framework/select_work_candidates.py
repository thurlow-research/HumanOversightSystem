def _emit(*parts: str) -> None:
    print("select_work_candidates: " + " ".join(parts), file=sys.stderr)


def _report_and_exit(
    repo: str,
    milestone: int,
    scanned: int,
    eligible: list,
    gated_reasons: Counter,
    gated_issue_numbers: list,
    authorized: dict,
    unevaluated_sufficient: int,
    unevaluated_cost_ceiling: int,
    cost_ceiling_named_issue: Optional[int],
    query_failed_issues: list,
    list_truncated: bool,
    tier_degraded: bool,
    tier_count: int,
    collaborator_bound_reached: bool,
    api_requests: int,
    walk_warn_lines: list,
    ceiling_refused_at_list: bool = False,
    edge_summary_unreadable: Sequence[tuple] = (),  # [(number, limb)]
    excluded: Sequence[tuple] = (),  # [(number, reason)]
    closed_blocker_failed: Collection[int] = (),  # subset of query_failed_issues
) -> int:
    gated_count = sum(gated_reasons.values())
    evaluated = len(eligible) + gated_count
    unevaluated = (
        unevaluated_sufficient
        + unevaluated_cost_ceiling
        + len(query_failed_issues)
        + len(edge_summary_unreadable)
    )
    # A Step C page refused by the request ceiling is, on its own, a bound
    # that truncated the candidate set (§2.3 Step C's REFUSED state;
    # revision 8) — complete=no even when nothing was fetched at all
    # (N=0 at --max-api-requests 0). This is forced independently of the
    # unevaluated/list-truncated/tier-degraded computation below, which
    # would otherwise read an empty, unreached set as trivially complete.
    # F36 (ops MUST_FIX): a collaborator-page-bound-truncated tier resolution
    # can only ever SHRINK the trusted set (AM-31), so it is completeness-
    # affecting exactly like the other rows here, never security-affecting.
    complete = (
        unevaluated == 0
        and not list_truncated
        and not tier_degraded
        and not ceiling_refused_at_list
        and not collaborator_bound_reached
    )

    for line in walk_warn_lines:
        _emit(line)

    if unevaluated > 0 or list_truncated:
        _emit(
            f"UNEVALUATED {unevaluated} of {scanned} records were not evaluated:",
            f"unevaluated:sufficient={unevaluated_sufficient}",
            f"unevaluated:cost-ceiling={unevaluated_cost_ceiling}",
            f"unevaluated:query-failed={len(query_failed_issues)}",
            f"unevaluated:list-truncated={'yes' if list_truncated else 'no'}",
            f"unevaluated:{UNEVALUATED_EDGE_SUMMARY}={len(edge_summary_unreadable)}",
        )
    for issue in query_failed_issues:
        suffix = " check=closed-blocker" if issue in closed_blocker_failed else ""
        _emit(f"WARN unevaluated:query-failed issue=#{issue}{suffix}")
    for issue, limb in edge_summary_unreadable[:_EXCLUDED_LIST_BOUND]:
        _emit(f"WARN unevaluated:{UNEVALUATED_EDGE_SUMMARY} issue=#{issue} limb={limb}")
    unreadable_more = len(edge_summary_unreadable) - _EXCLUDED_LIST_BOUND
    if unreadable_more > 0:
        _emit(f"WARN unevaluated:{UNEVALUATED_EDGE_SUMMARY} (+{unreadable_more} more)")
    if edge_summary_unreadable and len(edge_summary_unreadable) == scanned:
        _emit(
            f"WARN {UNEVALUATED_EDGE_SUMMARY}-on-every-record n={scanned} —",
            "the GitHub host may not return issue dependency / sub-issue",
            "summaries on the list endpoint; selection cannot determine",
            'blocked-ness (DEGRADED, not "no work")',
        )
    if cost_ceiling_named_issue is not None:
        _emit(f"unevaluated:cost-ceiling issue=#{cost_ceiling_named_issue}")
        _emit(f"budget-clamped-events-fetch issue=#{cost_ceiling_named_issue}")

    for issue, actor in sorted(authorized.items()):
        _emit(f"AUTHORIZED issue=#{issue} actor={actor} via=labeled")

    if list_truncated:
        _emit(
            f"WARN candidate-list-truncated pages={LIST_PAGE_BOUND} —",
            "at least",
            f"{LIST_PAGE_BOUND * 100} records matched; the total is UNKNOWN",
        )
    if tier_degraded:
        _emit(f"WARN tier-resolution-failed tiers={tier_count}")
    if collaborator_bound_reached:
        _emit(f"WARN collaborator-page-bound-reached pages={COLLABORATOR_PAGE_BOUND}")

    if excluded:
        by_reason = Counter(reason for _, reason in excluded)
        reason_counts = " ".join(f"{r}={by_reason[r]}" for r in NATIVE_EXCLUSION_REASONS)
        if by_reason[PARKED_LABEL]:  # absent when 0: the native literal line stays byte-stable
            reason_counts += f" {PARKED_LABEL}={by_reason[PARKED_LABEL]}"
        _emit(
            f"EXCLUDED {len(excluded)} in-milestone issues are not actionable",
            f"(not counted in scanned): {reason_counts}",
        )
        excluded_str = " ".join(f"#{n}({r})" for n, r in excluded[:_EXCLUDED_LIST_BOUND])
        excluded_more = len(excluded) - _EXCLUDED_LIST_BOUND
        if excluded_more > 0:
            excluded_str += f" (+{excluded_more} more)"
        _emit(f"EXCLUDED issues: {excluded_str}")
        closed_unverified = [n for n, r in excluded if r == NATIVE_EXCLUSION_REASONS[1]]
        for issue in closed_unverified[:_EXCLUDED_LIST_BOUND]:
            _emit(
                f"WARN blocker-closed-unverified issue=#{issue} —",
                "no closed blocker is satisfied by a merge to the default branch or",
                "a CODEOWNER close; a CODEOWNER may remove the dependency edge if",
                "the blocker is satisfied",
            )

    if not eligible and gated_count > 0:
        _emit(
            f"ALL-CANDIDATES-GATED {gated_count} of {scanned} in-milestone",
            "issues are held for human authorization",
        )
        reasons_str = " ".join(f"{tok}={cnt}" for tok, cnt in sorted(gated_reasons.items()))
        _emit(f"ALL-CANDIDATES-GATED reasons: {reasons_str}")
        shown = gated_issue_numbers[:20]
        more = len(gated_issue_numbers) - len(shown)
        issues_str = " ".join(f"#{n}" for n in shown)
        if more > 0:
            issues_str += f" (+{more} more)"
        _emit(f"ALL-CANDIDATES-GATED issues: {issues_str}")
        if not complete:
            _emit(
                f"ALL-CANDIDATES-GATED INCOMPLETE — {unevaluated} further",
                "records were not evaluated (see UNEVALUATED above); this",
                "count is a FLOOR",
            )

    _emit(
        f"repo={repo}",
        f"milestone={milestone}",
        f"scanned={scanned}",
        f"evaluated={evaluated}",
        f"eligible={len(eligible)}",
        f"authorized={len(authorized)}",
        f"gated={gated_count}",
        f"unevaluated={unevaluated}",
        f"api_requests={api_requests}",
        f"complete={'yes' if complete else 'no'}",
    )

    if complete is False and not eligible:
        return 3
    return 0


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main(argv: Optional[list] = None) -> int:
    parser = _build_parser()
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        # argparse's own usage-error exit is 2, which is consistent: a
        # malformed invocation is a fail-closed condition (§2.2).
        return exc.code if isinstance(exc.code, int) else 2

    effective_max_candidates = min(_DEFAULT_MAX_CANDIDATES, max(1, args.max_candidates))
    effective_max_api_requests = min(_DEFAULT_MAX_API_REQUESTS, max(0, args.max_api_requests))

    repo_root = str(_REPO_ROOT)
    budget = _Budget(effective_max_api_requests)

    try:
        config = _load_configuration(repo_root, args.repo, budget)
    except _ConfigFailure as exc:
        _emit(exc.token)
        if exc.remediation:
            _emit(exc.remediation)
        return 2
    except Exception:  # noqa: BLE001 — Step B's own catch-all (§2.3 Step B item 7)
        _emit("config-error")
        return 2

    # Step C — the paginated list query. `--label` is URL-encoded before
    # embedding: a space is a legal GitHub label character (e.g. "needs ai")
    # that `_label_name` does not and must not reject, but an unencoded space
    # produces a malformed querystring (cross-vendor second review, agy).
    encoded_label = urllib.parse.quote(args.label, safe="")

    def list_endpoint(page: int) -> str:
        return (
            f"repos/{args.repo}/issues?state=open&milestone={args.milestone}"
            f"&labels={encoded_label}&per_page=100&page={page}"
        )

    outcome = _fetch_pages(list_endpoint, LIST_PAGE_BOUND, budget)
    if outcome.state == "FAILED":
        _emit("list-query-failed")
        return 2

    filtered = _apply_free_filters(outcome.records)
    candidates_raw = filtered.kept
    scanned = len(candidates_raw) + len(filtered.unreadable)
    list_truncated = outcome.state == "BOUND-REACHED"
    ceiling_refused_at_list = outcome.state == "REFUSED"

    if ceiling_refused_at_list:
        # "The gate does not walk a partial list." Nothing is admitted.
        # Every fetched-and-filtered record counts as unevaluated:cost-ceiling
        # (§2.3 Step C REFUSED state). No WARN — the ceiling is routine. D2b
        # is free and already ran (§2.5): only `kept` records are
        # cost-ceiling; unreadable ones are their own named reason.
        return _report_and_exit(
            repo=args.repo,
            milestone=args.milestone,
            scanned=scanned,
            eligible=[],
            gated_reasons=Counter(),
            gated_issue_numbers=[],
            authorized={},
            unevaluated_sufficient=0,
            unevaluated_cost_ceiling=len(candidates_raw),
            cost_ceiling_named_issue=None,
            query_failed_issues=[],
            list_truncated=False,
            tier_degraded=config.tier_degraded,
            tier_count=config.tier_count,
            collaborator_bound_reached=config.collaborator_bound_reached,
            api_requests=budget.spent,
            walk_warn_lines=[],
            ceiling_refused_at_list=True,
            edge_summary_unreadable=filtered.unreadable,
            excluded=filtered.excluded,
        )

    # D3/D4/D-rank — free, computed over the whole (post-D1/D2) set.
    candidate_states = [
        _Candidate(
            number=r.get("number"),
            title=_sanitize_title(r.get("title") or ""),
            rank=_rank(r),
            verdict=requester_verdict(r, config.trusted_set),
            record=r,
        )
        for r in candidates_raw
    ]
    stages = _started_stages(repo_root, [c.number for c in candidate_states])
    if stages is None:
        _emit("WARN started-signal-unavailable")
    else:
        for c in candidate_states:
            c.stage = stages.get(c.number, _STAGE_NONE)
    walk_order = sorted(candidate_states, key=lambda c: (c.stage, c.rank, -c.number))

    walk_result = _walk(
        walk_order,
        repo=args.repo,
        label=args.label,
        codeowners=config.codeowners,
        bots=config.bots,
        budget=budget,
        max_candidates=effective_max_candidates,
        closed_blocker_check=frozenset(filtered.closed_blocker_check),
        repo_root=repo_root,
    )
    # Closed-blocker exclusions decided in the walk were counted in `scanned`
    # (they were kept for the walk); like D2b exclusions they are reported as
    # excluded and not counted in scanned, so the counting identities hold.
    all_excluded = [*filtered.excluded, *walk_result.excluded]
    scanned -= len(walk_result.excluded)

    emit_order = sorted(walk_result.eligible, key=lambda c: (c.stage, c.rank, c.number))
    for c in emit_order:
        marker = f" [started:{_STAGE_NAMES[c.stage]}]" if c.stage in _STAGE_NAMES else ""
        print(f"#{c.number} [{_PRIORITY_NAMES[c.rank]}]{marker} {c.title}")
    _emit(
        f"STARTED branch={sum(c.stage == _STAGE_BRANCH for c in emit_order)}",
        f"design={sum(c.stage == _STAGE_DESIGN for c in emit_order)}",
    )

    return _report_and_exit(
        repo=args.repo,
        milestone=args.milestone,
        scanned=scanned,
        eligible=walk_result.eligible,
        gated_reasons=walk_result.gated_reasons,
        gated_issue_numbers=walk_result.gated_issue_numbers,
        authorized=walk_result.authorized,
        unevaluated_sufficient=walk_result.unevaluated_sufficient,
        unevaluated_cost_ceiling=walk_result.unevaluated_cost_ceiling,
        cost_ceiling_named_issue=walk_result.cost_ceiling_named_issue,
        query_failed_issues=walk_result.query_failed_issues,
        list_truncated=list_truncated,
        tier_degraded=config.tier_degraded,
        tier_count=config.tier_count,
        collaborator_bound_reached=config.collaborator_bound_reached,
        api_requests=budget.spent,
        walk_warn_lines=walk_result.warn_lines,
        edge_summary_unreadable=filtered.unreadable,
        excluded=all_excluded,
        closed_blocker_failed=walk_result.closed_blocker_failed,
    )


if __name__ == "__main__":  # pragma: no cover - CLI entry, exercised via subprocess only
    sys.exit(main())
