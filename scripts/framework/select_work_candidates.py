class _ConfigFailure(Exception):
    def __init__(self, token: str, remediation: str):
        super().__init__(token, remediation)
        self.token = token
        self.remediation = remediation


@dataclass
class _Configuration:
    trusted_set: Any
    codeowners: set
    bots: set
    tier_degraded: bool
    tier_count: int
    collaborator_bound_reached: bool


def _load_configuration(repo_root: str, repo: str, budget: _Budget) -> _Configuration:
    """Step B, in order (§2.3): bots, codeowners, apps, roster, then the
    LAZY, conditional collaborator fetch (H3, §1.3.2). Raises
    `_ConfigFailure` for every fail-closed row; tier resolution never raises
    (AM-31: a degraded tier resolution can only shrink the trusted set)."""
    # B1 — bots.
    bots = load_bot_accounts(repo_root)
    if not bots:
        if machine_accounts_file_absent(repo_root):
            raise _ConfigFailure(
                "machine-accounts-file-absent",
                "this file is required by the work-selection gate, is not "
                "shipped by HOS and is not produced by the installer; create "
                "it with BOT_WORKER_USERNAME, BOT_OVERSEER_USERNAME, "
                "BOT_HUMAN_USERNAME and COPILOT_BOT_LOGIN",
            )
        raise _ConfigFailure(
            "bot-accounts-empty",
            "no bot accounts resolved; the gate cannot distinguish a bot "
            "from a human and refuses to run",
        )

    # B2 — CODEOWNERS. Three distinct facts, three distinct tokens (AM-34).
    codeowners_path = Path(repo_root) / ".github" / "CODEOWNERS"
    if not codeowners_path.is_file():
        raise _ConfigFailure(
            "codeowners-file-absent",
            "create `.github/CODEOWNERS` naming at least one individual "
            "GitHub user who may authorize work",
        )
    try:
        codeowners = codeowners_humans(repo_root)
    except OSError as exc:
        raise _ConfigFailure(
            "codeowners-unreadable",
            "the file exists but could not be read; check permissions",
        ) from exc
    if not codeowners:
        raise _ConfigFailure(
            "codeowners-no-individual-human",
            "this file is valid but lists only team handles; team handles "
            "do not confer authorization authority. Add at least one "
            "individual user handle.",
        )

    # B3 — apps.
    apps = load_trusted_apps(repo_root)
    if not apps:
        if machine_accounts_file_absent(repo_root):
            raise _ConfigFailure(
                "machine-accounts-file-absent",
                "this file is required by the work-selection gate, is not "
                "shipped by HOS and is not produced by the installer; create "
                "it with BOT_WORKER_USERNAME, BOT_OVERSEER_USERNAME, "
                "BOT_HUMAN_USERNAME and COPILOT_BOT_LOGIN",
            )
        raise _ConfigFailure("trusted-apps-empty", "no HOS App identities resolved")

    # B4 — roster.
    try:
        policy = load_trusted_requesters(repo_root)
    except OSError as exc:
        raise _ConfigFailure("roster-unreadable", "") from exc

    # B5 — LAZY, conditional collaborator fetch (H3). Zero cost when no tier
    # is listed. Any failure is completeness-affecting, never security
    # (AM-31): it can only ever SHRINK the trusted set.
    collaborators = None
    tier_degraded = False
    collaborator_bound_reached = False
    if policy.tiers:
        before = budget.spent
        collaborators, _ = fetch_collaborators(repo, budget.refuse, budget.record)
        delta = budget.spent - before
        if collaborators is None:
            # A ceiling refusal (ANY page, including the first) is quiet by
            # construction (fetch_collaborators never prints). A genuine
            # transport/parse failure is not. `fetch_collaborators`'s
            # contract does not expose which case fired directly, so this
            # is inferred: `delta == 0` is unambiguous (page 1 itself was
            # refused before any request); `delta > 0` with the ceiling now
            # exhausted is read as "the ceiling caused this" too. The one
            # imprecision this leaves — a genuine failure landing on the
            # exact request that also exhausts the ceiling — fails toward
            # silence on a completeness-only signal, never toward a security
            # claim, which is the same class of accepted imprecision §1.4
            # rule 4(a) states for the events-fetch clamp.
            if delta == 0 or budget.refuse():
                pass
            else:
                tier_degraded = True
        elif delta == 3 and len(collaborators) == 300:
            # COLLABORATOR_PAGE_BOUND (3) pages, all full (300 collaborators
            # returned) — the exact-multiple imprecision §1.4 rule 4(a)
            # accepts elsewhere: indistinguishable from a repo with exactly
            # 300 collaborators, and it fails safe (an under-resolved tier
            # only shrinks who is trusted).
            collaborator_bound_reached = True

    trusted_set = load_trusted_set(repo_root, collaborators=collaborators)
    return _Configuration(
        trusted_set=trusted_set,
        codeowners=codeowners,
        bots=bots,
        tier_degraded=tier_degraded,
        tier_count=len(policy.tiers),
        collaborator_bound_reached=collaborator_bound_reached,
    )


