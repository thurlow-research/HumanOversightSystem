class _Budget:
    """`api_requests <= effective_ceiling` holds by construction: the stop
    test runs BEFORE every request, and the counter increments AFTER a
    request returns, successfully or not (§2.2.1)."""

    def __init__(self, ceiling: int):
        self.ceiling = ceiling
        self.spent = 0

    def refuse(self) -> bool:
        return self.spent >= self.ceiling

    def record(self) -> None:
        self.spent += 1


