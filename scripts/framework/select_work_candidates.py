# The per-page fetch rule (§1.4, revision 8 / RP5-1) — shared by Step C's
# issue list and D5.2's events fetch.
# ---------------------------------------------------------------------------


class _GhFailure(Exception):
    """One page's `gh api` invocation could not be parsed."""


def _run_gh(endpoint: str) -> Any:
    """Issue exactly ONE `gh api <endpoint>` GET and return parsed JSON.

    Shells out directly with `subprocess.run`, following the precedent
    already set in this directory by `require_human_approval.py`'s
    `reviews_from_gh` / `require_human_approval.py:_fetch_reviews` (§2.2's
    "GitHub access" note) — this module does NOT import
    `scripts/automation/lib/github.py`'s `_run_gh`, which sits on an
    unprotected surface (§1.1)."""
    try:
        result = subprocess.run(
            ["gh", "api", endpoint],
            capture_output=True,
            text=True,
            check=False,
            timeout=_GH_SUBPROCESS_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise _GhFailure(str(exc)) from exc
    if result.returncode != 0:
        raise _GhFailure(result.stderr.strip())
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise _GhFailure(str(exc)) from exc


@dataclass
class _FetchOutcome:
    records: list
    state: str  # "COMPLETE" | "BOUND-REACHED" | "REFUSED" | "FAILED"
    error: str = ""


def _fetch_pages(
    endpoint_for_page: Callable[[int], str], page_bound: int, budget: _Budget
) -> _FetchOutcome:
    """Fetch pages 1..page_bound, one `gh api` invocation each, per §1.4's
    per-page fetch rule. Before every page: (a) the page-bound range below
    already enforces the page bound; (b) the request ceiling's stop test.
    A page with fewer than 100 raw items ends the history (COMPLETE)."""
    collected: list = []
    for page in range(1, page_bound + 1):
        if budget.refuse():
            return _FetchOutcome(collected, "REFUSED")
        try:
            batch = _run_gh(endpoint_for_page(page))
        except _GhFailure as exc:
            budget.record()
            return _FetchOutcome(collected, "FAILED", str(exc))
        budget.record()
        if not isinstance(batch, list):
            return _FetchOutcome(collected, "FAILED", "non-list response")
        collected.extend(batch)
        if len(batch) < 100:
            return _FetchOutcome(collected, "COMPLETE")
    return _FetchOutcome(collected, "BOUND-REACHED")


# ---------------------------------------------------------------------------
# Step B — configuration (all fail-closed except tier resolution, AM-31)
