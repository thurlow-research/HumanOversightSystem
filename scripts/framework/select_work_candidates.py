_SHA_RE = re.compile(r"^[0-9a-f]{40}$")
_DEFAULT_BRANCH_REF = "refs/remotes/origin/main"  # same ref _started_stages uses


def _is_default_branch_ancestor(repo_root: str, sha: Any) -> Optional[bool]:
    """Tri-state, free (local git): True iff `sha` is an ancestor of origin/main,
    False iff it is not (or is malformed: not attributable), None (UNKNOWN) when
    git cannot answer -- unknown object, missing ref, timeout. `merge-base A B`
    prints A exactly when A is an ancestor of B; exit 0/1 are answers, any other
    exit (128: unknown object / missing ref) is a `_GitFailure`. (`_git` returns
    stdout only, so this is `merge-base`, not `merge-base --is-ancestor`.)"""
    if not isinstance(sha, str) or not _SHA_RE.match(sha.lower()):
        return False
    try:
        out = _git(repo_root, "merge-base", sha.lower(), _DEFAULT_BRANCH_REF, ok_codes=(0, 1))
    except _GitFailure:
        return None
    return out.strip() == sha.lower()


_UNKNOWN = "unknown"  # blocker_closure_satisfied: undetermined (git/GraphQL could not answer)
_FAILED = object()  # per-walk cache marker: this blocker's evidence could not be fetched/decided

# One default-branch name, derived from the single ref constant above (no second
# literal): the GraphQL closer's `baseRefName` must equal it.
_DEFAULT_BRANCH_NAME = _DEFAULT_BRANCH_REF.rsplit("/", 1)[-1]

# The closer lookup (#2173 ruling, C0-probed 2026-11-03). A module-level literal:
# owner, name and number reach `gh` ONLY as separate variable arguments, never
# interpolated into this text.
_CLOSER_QUERY = (
    "query($owner:String!,$name:String!,$number:Int!){"
    "repository(owner:$owner,name:$name){"
    "issue(number:$number){"
    "timelineItems(itemTypes:[CLOSED_EVENT], last:1){"
    "nodes{ ... on ClosedEvent{ createdAt stateReason "
    "closer{ __typename "
    "... on PullRequest{ number merged mergedAt baseRefName "
    "baseRepository{ nameWithOwner } mergeCommit{ oid } } "
    "... on Commit{ oid } } } } } } }"
)


class _BudgetRefused(Exception):
    """The request ceiling stopped the closer lookup: the record is REFUSED
    (degraded), never UNKNOWN and never a determined "no"."""


def _run_graphql(owner: str, name: str, number: int) -> Any:
    """Issue exactly ONE `gh api graphql` call and return the parsed JSON.
    `owner` and `name` go as raw-string variables (`-f`: no `@file` or type
    coercion), `number` as a typed `Int` (`-F`); the query is never built from
    them."""
    try:
        result = subprocess.run(
            [
                "gh",
                "api",
                "graphql",
                "-f",
                f"query={_CLOSER_QUERY}",
                "-f",
                f"owner={owner}",
                "-f",
                f"name={name}",
                "-F",
                f"number={number}",
            ],
            capture_output=True,
            text=True,
            check=False,
            timeout=_GH_SUBPROCESS_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise _GhFailure(str(exc)) from exc
    if result.returncode != 0:
        raise _GhFailure(result.stderr.strip())
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise _GhFailure(str(exc)) from exc


def _fetch_closer_node(repo: str, number: int, budget: _Budget) -> Optional[dict]:
    """The last `ClosedEvent` node of issue `number`, or None (UNKNOWN) on any
    transport/shape failure. Exactly one request: the stop test runs first
    (`_BudgetRefused`), the counter increments after the call, success or not.
    UNKNOWN covers: non-zero exit, timeout, non-JSON, a non-empty `errors`, a
    missing/non-dict `data.repository.issue`, `nodes` not a one-item list."""
    owner, sep, name = repo.partition("/")
    if not sep or not owner or not name:
        return None
    if budget.refuse():
        raise _BudgetRefused
    try:
        payload = _run_graphql(owner, name, number)
    except _GhFailure:
        budget.record()
        return None
    budget.record()
    if not isinstance(payload, dict) or payload.get("errors"):
        return None
    data = payload.get("data")
    repository = data.get("repository") if isinstance(data, dict) else None
    issue = repository.get("issue") if isinstance(repository, dict) else None
    items = issue.get("timelineItems") if isinstance(issue, dict) else None
    nodes = items.get("nodes") if isinstance(items, dict) else None
    if not isinstance(nodes, list) or len(nodes) != 1 or not isinstance(nodes[0], dict):
        return None
    return nodes[0]


def _closer_attribution(
    node: dict, rest_closed_at: Any, repo: str, is_ancestor: Callable[[str], Optional[bool]]
) -> Optional[str]:
    """Merge attribution from GitHub's recorded cause, `ClosedEvent.closer`:
    "merge", None (determined: not a default-branch merge) or `_UNKNOWN`.
    The node must be the very closure the REST events show (equal `createdAt`);
    a mismatch is a race with a reopen/re-close, so undetermined. No actor
    check: the closer is the cause, and a bot merger is legitimate."""
    if not rest_closed_at or node.get("createdAt") != rest_closed_at:
        return _UNKNOWN
    closer = node.get("closer")
    if closer is None:
        return None
    if not isinstance(closer, dict):
        return _UNKNOWN
    typename = closer.get("__typename")
    if typename == "PullRequest":
        base_repo = closer.get("baseRepository")
        base_repo = base_repo if isinstance(base_repo, dict) else {}
        name_with_owner = base_repo.get("nameWithOwner")
        merge_commit = closer.get("mergeCommit")
        sha = merge_commit.get("oid") if isinstance(merge_commit, dict) else None
        if (
            closer.get("merged") is not True
            or closer.get("baseRefName") != _DEFAULT_BRANCH_NAME
            or not isinstance(name_with_owner, str)
            or name_with_owner.lower() != repo.lower()
        ):
            return None
    elif typename == "Commit":
        sha = closer.get("oid")
    else:
        return None
    answer = is_ancestor(sha) if isinstance(sha, str) else False
    if answer is None:
        return _UNKNOWN
    return "merge" if answer else None


# GitHub stamps the issue's `closed_at` and the `closed` timeline event up to a
# second apart (live probe 2026-11-03: #1666, #2194, #1236, #2117 differ by 1s;
# #1532, #2196, #2147 are equal; the event is never earlier). Exact equality
# would FAIL most real closures, so the binding allows a small bounded skew.
_CLOSURE_SKEW_SECONDS = 2


def _utc_seconds(stamp: Any) -> Optional[float]:
    """Epoch seconds of a UTC ISO-8601 `...Z` timestamp, or None if unparseable."""
    if not isinstance(stamp, str):
        return None
    try:
        parsed = datetime.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ")
    except ValueError:
        return None
    return parsed.replace(tzinfo=timezone.utc).timestamp()


def _closure_bound(event_at: Any, closed_at: Any) -> bool:
    """True iff the `closed` event is the listed closure: 0 <= event - closed_at
    <= `_CLOSURE_SKEW_SECONDS`. Unparseable either side or outside the window is False."""
    event_s, listed_s = _utc_seconds(event_at), _utc_seconds(closed_at)
    if event_s is None or listed_s is None:
        return False
    return 0 <= event_s - listed_s <= _CLOSURE_SKEW_SECONDS


def blocker_closure_satisfied(
    events: Any,
    codeowners_set: set,
    bots: set,
    is_ancestor: Callable[[str], Optional[bool]],
    closer_lookup: Callable[[], Optional[dict]],
    repo: str,
    closed_at: str,
) -> Optional[str]:
    """Whether a blocker's closure satisfies a `blocked_by` edge, over an
    ALREADY-FETCHED events list (no network inside the predicate: the one paid
    lookup is the injected `closer_lookup`). Returns "merge", "codeowner", None
    (unsatisfied) or `_UNKNOWN` (undetermined, never a pass and never an
    exclusion). The caller has already required state=closed and
    state_reason=completed. Judged on the LAST `closed` event (an issue can be
    reopened and closed again). `closed_at` is the closure the `blocked_by`
    listing reported: the last `closed` event must be that closure (equal
    `created_at`), else the evidence is for a different closure and the answer
    is `_UNKNOWN`. Cheapest evidence first:
      1. that event's non-null `commit_id` (GitHub's recorded cause: a closing
         keyword in a commit pushed to the default branch) that is an ancestor
         of the default branch -> "merge"; with a commit present the closure
         is decided on it alone;
      2. the closer is an individual human CODEOWNER, not a bot -> "codeowner";
      3. otherwise (no commit on the event) ONE `closer_lookup()` of GraphQL
         `ClosedEvent.closer`: a PR merged into the default branch of THIS
         repo whose merge commit is an ancestor of it, or such a commit -> "merge".
    A matching timestamp or a `referenced` event is never attribution. The
    lookup returns the node dict or None (UNKNOWN); it may raise
    `_BudgetRefused`, which the caller maps to REFUSED."""
    if not isinstance(events, list):
        return None
    closed = [e for e in events if isinstance(e, dict) and e.get("event") == "closed"]
    if not closed:
        return None
    last = closed[-1]
    if not _closure_bound(last.get("created_at"), closed_at):
        return _UNKNOWN  # the events describe a different closure than the one listed
    if any(
        isinstance(e, dict) and e.get("event") == "reopened"
        for e in events[events.index(last) + 1 :]
    ):
        return _UNKNOWN  # reopened after that closure: it is not the current one
    commit = last.get("commit_id")
    ancestry = is_ancestor(commit) if commit else False
    if ancestry is True:
        return "merge"
    actor = last.get("actor")
    actor = actor if isinstance(actor, dict) else {}
    login = actor.get("login") or ""
    if (
        login
        and not is_bot_reviewer(login, actor.get("type", ""), bots)
        and login.lower() in codeowners_set
    ):
        return "codeowner"
    if commit:
        return _UNKNOWN if ancestry is None else None
    node = closer_lookup()
    if node is None:
        return _UNKNOWN
    return _closer_attribution(node, last.get("created_at"), repo, is_ancestor)


def _same_repo(repository_url: Any, repo: str) -> bool:
    """True iff a blocker's `repository_url` ends in exactly `/repos/{repo}`
    (case-insensitive; host-agnostic so GHES works). `blocked_by` can return
    issues of OTHER repositories, whose events this check must never judge by
    bare issue number. Missing or malformed is False."""
    if not isinstance(repository_url, str):
        return False
    return repository_url.lower().rstrip("/").endswith(f"/repos/{repo.lower()}") and (
        repository_url.lower().rstrip("/").count("/repos/") == 1
    )


@dataclass
class _ClosedBlockerCheck:
    state: str  # "SATISFIED" | "UNSATISFIED" | "FAILED" | "REFUSED"
    satisfied_by: list = field(default_factory=list)  # [(blocker number, "merge"|"codeowner")]
    fetched: bool = False  # at least one request was spent on this record


def _check_closed_blockers(
    cand: "_Candidate",
    repo: str,
    repo_root: str,
    codeowners: set,
    bots: set,
    budget: _Budget,
    verdicts: dict,
) -> _ClosedBlockerCheck:
    """The paid check: every request counts against `budget`. REFUSED / FAILED /
    a truncated fetch are never a pass and never an exclusion. `verdicts`
    caches determined answers per (blocker number, closed_at) so a closure shared
    by several dependents is paid for once and a re-closed blocker is re-judged."""
    spent_before = budget.spent

    def _result(state: str, by: Optional[list] = None) -> _ClosedBlockerCheck:
        return _ClosedBlockerCheck(state, by or [], budget.spent > spent_before)

    def _blockers_endpoint(page: int) -> str:
        return f"repos/{repo}/issues/{cand.number}/dependencies/blocked_by?per_page=100&page={page}"

    listed = _fetch_pages(_blockers_endpoint, BLOCKER_PAGE_BOUND, budget)
    if listed.state in ("FAILED", "REFUSED"):
        return _result(listed.state)
    blockers = listed.records
    # Validate before anything else: a record we cannot read is never dropped
    # (that would judge a list we cannot fully see), and an unvalidated `number`
    # must not reach the events path or the cache key. `bool` is an `int`.
    if any(
        not isinstance(b, dict)
        or not isinstance(b.get("number"), int)
        or isinstance(b.get("number"), bool)
        or b["number"] <= 0
        for b in blockers
    ):
        return _result("FAILED")
    # Decide the free rejections first: an unsatisfiable blocker settles the
    # record as excluded without paying for any events.
    for blocker in blockers:
        if (
            not _same_repo(blocker.get("repository_url"), repo)
            or blocker.get("state") != "closed"
            or blocker.get("state_reason") != "completed"
        ):
            return _result("UNSATISFIED")
    # The closure being judged is identified by `closed_at`; without it a cached
    # verdict could not be tied to one closure (reopen + re-close mid-walk).
    if any(not isinstance(b.get("closed_at"), str) or not b["closed_at"] for b in blockers):
        return _result("FAILED")
    if listed.state == "BOUND-REACHED" or not blockers:
        return _result("FAILED")  # cannot see every blocker / nothing to judge: unevaluated
    by: list = []
    for blocker in blockers:
        number = blocker.get("number")
        closed_at = blocker["closed_at"]
        key = (number, closed_at)  # one verdict per CLOSURE, not per issue number
        if verdicts.get(key) is _FAILED:
            return _result("FAILED")  # already failed this walk: no re-fetch
        if key not in verdicts:

            def _events_endpoint(page: int, num: Any = number) -> str:
                return f"repos/{repo}/issues/{num}/events?per_page=100&page={page}"

            fetched = _fetch_pages(_events_endpoint, EVENTS_PAGE_BOUND, budget)
            if fetched.state == "REFUSED":
                return _result("REFUSED")
            if fetched.state != "COMPLETE":
                # FAILED, or BOUND-REACHED (the last `closed` event may lie beyond the bound).
                verdicts[key] = _FAILED
                return _result("FAILED")
            try:
                verdict = blocker_closure_satisfied(
                    fetched.records,
                    codeowners,
                    bots,
                    lambda sha: _is_default_branch_ancestor(repo_root, sha),
                    functools.partial(_fetch_closer_node, repo, number, budget),
                    repo,
                    closed_at,
                )
            except _BudgetRefused:
                return _result("REFUSED")
            verdicts[key] = _FAILED if verdict == _UNKNOWN else verdict
            if verdict == _UNKNOWN:
                return _result("FAILED")
        if verdicts[key] is None:
            return _result("UNSATISFIED")
        by.append((number, verdicts[key]))
    return _result("SATISFIED", by)


def _walk(
    walk_order: list,
    repo: str,
    label: str,
    codeowners: set,
    bots: set,
    budget: _Budget,
    max_candidates: int,
    closed_blocker_check: frozenset = frozenset(),
    repo_root: Optional[str] = None,
) -> _WalkResult:
    result = _WalkResult()
    repo_root = repo_root if repo_root is not None else str(_REPO_ROOT)
    blocker_verdicts: dict = {}
    i = 0
    n = len(walk_order)
    while i < n:
        cand = walk_order[i]
        if len(result.eligible) >= max_candidates:
            result.unevaluated_sufficient += n - i
            result.stopped = True
            return result
        if cand.number in closed_blocker_check:
            # Paid, and BEFORE the trust test: an unsatisfied record is excluded,
            # never counted as gated (#2173).
            check = _check_closed_blockers(
                cand, repo, repo_root, codeowners, bots, budget, blocker_verdicts
            )
            if check.state == "REFUSED":
                # Same cost-ceiling tail as D5's refused events fetch.
                if check.fetched:
                    result.cost_ceiling_named_issue = cand.number
                result.unevaluated_cost_ceiling += n - i
                result.stopped = True
                return result
            if check.state == "FAILED":
                result.query_failed_issues.append(cand.number)
                result.closed_blocker_failed.add(cand.number)
                i += 1
                continue
            if check.state == "UNSATISFIED":
                result.excluded.append((cand.number, NATIVE_EXCLUSION_REASONS[1]))
                i += 1
                continue
            for blocker, how in check.satisfied_by:
                result.warn_lines.append(
                    f"blocker-satisfied issue=#{cand.number} blocker=#{blocker} by={how}"
                )
        if cand.verdict.trusted:
            result.eligible.append(cand)
            i += 1
            continue

        def _events_endpoint(page: int, num: int = cand.number) -> str:
            return f"repos/{repo}/issues/{num}/events?per_page=100&page={page}"

        # No pre-check of `budget.refuse()` here: `_fetch_pages`'s own rule
        # 3(b) stop test runs before page 1 exactly as it runs before every
        # later page, so calling it unconditionally is equivalent and costs
        # no extra `gh` invocation when the ceiling is already exhausted
        # (its internal stop test short-circuits before any request).
        outcome = _fetch_pages(_events_endpoint, EVENTS_PAGE_BOUND, budget)
        if outcome.state == "FAILED":
            result.query_failed_issues.append(cand.number)
            i += 1
            continue
        actor = verify_codeowner_actor(outcome.records, codeowners, bots, label)
        if outcome.state == "REFUSED":
            if actor is not None:
                result.eligible.append(cand)
                result.authorized[cand.number] = actor
                i += 1
                continue
            # The ceiling stop (§2.3 D5.1 / §1.4 rule 4). This record and
            # everything after it are unevaluated:cost-ceiling, and the walk
            # ends COMPLETELY here — but the record is named on its own line
            # ONLY for a genuine bite: at least one full events page was
            # already fetched for it (`outcome.records` non-empty) before
            # the next page was refused with no match (§1.2 pt 7's "one
            # exception to 'cost-ceiling is only a count'"). When `L = 0`
            # (no events page was ever requested for this record — the
            # ceiling was already exhausted at the candidate boundary),
            # rule 4(a) is explicit: "the record is part of the unreached
            # tail," and it is NOT named — it is counted like every other
            # record in the tail, no differently.
            if outcome.records:
                result.cost_ceiling_named_issue = cand.number
            result.unevaluated_cost_ceiling += n - i
            result.stopped = True
            return result
        # COMPLETE or BOUND-REACHED: a determination.
        if actor is not None:
            result.eligible.append(cand)
            result.authorized[cand.number] = actor
        else:
            if outcome.state == "BOUND-REACHED":
                result.warn_lines.append(f"WARN events-page-bound-reached issue=#{cand.number}")
            result.gated_reasons["no-codeowner-actor"] += 1
            result.gated_issue_numbers.append(cand.number)
        i += 1
    return result


