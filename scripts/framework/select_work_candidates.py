#!/usr/bin/env python3
"""select_work_candidates.py — the deterministic, author-trust-gated
work-selection entry point (S2 of #1540, fix path for #1539).

Protected surface. AD-3's single entry point: query + trust + authorization +
ordering. This is the ONLY way work candidates are produced — both
`bin/hos-cron`'s pre-computed context block and `bootstrap/worker-cron-prompt.md`
Step 2's fallback invoke this exact command (§2.4, §2.5 of
docs/v0.7.0/TECHNICAL-DESIGN-1540-S1-S2-intake-trust-gate.md, revision 8).

It never writes to GitHub — no labels, no comments, no state, no cache, no
resume cursor (FR7/AD-4: every cycle re-derives from live state).

Exit codes (§2.2, AM-32):
  0 = a determination the gate can STATE the extent of, with at least one
      candidate emitted OR with `complete=yes`.
  3 = DEGRADED. `complete=no` AND stdout EMPTY. The gate ran, could not
      finish looking, and is saying so rather than claiming an empty queue.
      NOT an error, NOT fail-closed.
  2 = fail closed. stdout EMPTY. Exactly one `select_work_candidates: <token>`
      line on stderr (plus a remediation line for the four F1/F2/F3/F4 rows).

The algorithm's order is part of the contract (§2.3, AM-19/AM-29):
  A args -> B config (incl. LAZY tier resolution) -> C list (PAGINATED)
  D1 drop PR records (free) -> D2 drop EXCLUDED_LABELS; report PARKED_LABEL (free)
  D2b drop native-blocked / parent records; set aside unreadable-summary records (free)
  D3 requester_verdict (free) -> D4 trusted -> eligible, zero cost (free)
  D-rank: rank the WHOLE set (free) -- precedes D5, never move it below
  D5: walk the ranked list; pay per untrusted record (events query)
  E: sort the admitted set into emission order -> F: report

Two orders, deliberately different (AM-29, TP-1):
  WALK  = (stage, rank, number DESC)  -- a reachability decision, total by
          construction (issue numbers are unique; no tie-break needed).
  EMIT  = (stage, rank, number ASC)   -- #901's documented FIFO-within-band.

`stage` is the "already started" key (#2155): 0 = a local `worker-<N>-*`
branch whose content is not yet on origin/main (merging it into origin/main
would change the tree, or conflict -- a content test, so squash, rebase and
cherry-pick landings all count as landed), 1 = a TECHNICAL-DESIGN for N is
merged on origin/main (an ADR alone leaves a spec still to write), 2 = neither.
It sorts BEFORE priority so started work finishes before new work
begins, and it leads the WALK order so the max-candidates clamp cannot drop a
started low-priority issue. It costs zero API requests
(local git against `_REPO_ROOT` only) and is fail-safe: if git cannot answer,
every candidate is stage 2 and one WARN line is emitted -- it only reorders,
never drops a candidate or changes an exit code.

Every bounded list fetch in this module issues ONE `gh api` invocation PER
PAGE, with `page=` and `per_page=100` literally in the endpoint's query
string -- never `--paginate` (which on gh 2.45.0 fetches every page with no
cap and cannot be stopped by a request-budget stop test) and never `-f`/`-F`
(which silently switches the request method to POST). A page shorter than
100 raw items ends the history (§1.4's per-page fetch rule, revision 8 /
RP5-1). No `--repo-root` flag exists (AD-13): the repo root is derived from
this file's own location, never from a caller-supplied path.

The authorizing act (FR29(b), AR-9 — the consumer-facing statement this
shipped module carries so a consumer receiving the gate is not left to guess
what it does). Applying the `needs-ai` label (or whatever `--label` names) to
an issue, from your own GitHub account, STARTS AUTONOMOUS WORK ON THAT
ISSUE. This INCLUDES issues you did not author and whose content you do not
control — the gate never treats an issue's body or its labels as evidence of
who filed it. The act does NOT make the issue's author trusted, and it does
NOT make the issue's body trustworthy: the gate never reads an issue's body,
and requester trust and live authorization are evaluated independently of
one another. Two preconditions this gate requires and neither is shipped nor
generated by an installer: (1) `.github/CODEOWNERS` must name at least one
INDIVIDUAL human GitHub handle — a file naming only `org/team` patterns
confers no authorization authority and the gate refuses to run rather than
silently authorize nothing forever; (2) `scripts/framework/machine-accounts.env`
must exist, naming `BOT_WORKER_USERNAME`, `BOT_OVERSEER_USERNAME`,
`BOT_HUMAN_USERNAME` and `COPILOT_BOT_LOGIN` — its absence stops work
selection entirely. A CLI-only operator with no browser session is not
stranded: the authorizing act may be performed with a personal-access-token
`gh` invocation under your own login (`gh issue edit <n> --add-label
needs-ai`, after removing it first if it is already present, since a
re-applied label produces no new event to verify).

Native GitHub issue dependencies and sub-issues gate selection (ADR-1644
AD-C4). An issue with an OPEN blocking dependency (`blocked by`) is not
selected, and neither is an issue that has sub-issues; both cost no request,
because both are read from the list record. An issue whose blockers are all
CLOSED is not excluded for free: the paid satisfaction check (#2173, thin
T3.3) runs when the walk reaches it. A closed blocker is satisfied iff it
closed as `completed` AND the closure is attributable to a merge onto
origin/main or to an individual human CODEOWNER; otherwise the issue stays
excluded `blocker-closed-unverified`. The check's requests count against the
budget, and running out of budget is DEGRADED, never a pass. A blocker from
another repository is never satisfied. If the host does
not return these summaries, selection reports DEGRADED (exit 3) rather than
assume "not blocked". On such a host (for example, a GitHub
Enterprise Server version without issue dependencies), this happens **on
every run**, and no new issue work is selected until the host returns them.
An issue that has sub-issues stays unselected even after all of them close.
To make it selectable, close it or remove its sub-issue links.
"""

